import asyncio
from logging.config import fileConfig

from sqlalchemy import pool
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import create_async_engine

from alembic import context

import app.creator.model  # noqa: F401  registers every model on the metadata
from common.model import MappedBase
from core.conf import settings

config = context.config
if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = MappedBase.metadata


def include_object(obj, name, type_, reflected, compare_to):
    # views are created with SQL in the migrations, never autogenerated as tables
    return not (type_ == 'table' and obj.info.get('is_view'))


def configure(**kwargs) -> None:
    context.configure(
        target_metadata=target_metadata,
        include_object=include_object,
        include_schemas=True,
        include_name=lambda name, type_, parent: type_ != 'schema' or name == settings.DATABASE_SCHEMA,
        version_table_schema=settings.DATABASE_SCHEMA,
        **kwargs,
    )


def run_migrations_offline() -> None:
    configure(url=settings.SQLALCHEMY_DATABASE_URL, literal_binds=True, dialect_opts={'paramstyle': 'named'})
    with context.begin_transaction():
        context.run_migrations()


def do_run_migrations(connection: Connection) -> None:
    configure(connection=connection)
    with context.begin_transaction():
        context.run_migrations()


async def run_async_migrations() -> None:
    # The schema is named like the DB user, so Postgres' default "$user" search_path would make it the
    # default schema and reflection would miss the schema-qualified models. Keep it explicit.
    engine = create_async_engine(settings.SQLALCHEMY_DATABASE_URL, poolclass=pool.NullPool,
                                 connect_args={'options': '-c search_path=public'})
    async with engine.connect() as connection:
        # the version table lives in the schema, so it has to exist before Alembic looks for it
        await connection.exec_driver_sql(f'CREATE SCHEMA IF NOT EXISTS {settings.DATABASE_SCHEMA}')
        await connection.commit()
        await connection.run_sync(do_run_migrations)
    await engine.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    asyncio.run(run_async_migrations())
